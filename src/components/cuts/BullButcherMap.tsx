export type BullButcherMapProps = {
  imageHref?: string;
  className?: string;
  activeZoneId?: string | null;
  onZoneClick?: (zone: BullZone) => void;
  showLabels?: boolean;
};

export default function BullButcherMap({
  imageHref = "/images/bulle-freigestellt.png", // gespiegeltes (Kopf-links) Bild hier ablegen
  className = "w-full h-auto",
  activeZoneId = null,
  onZoneClick,
  showLabels = true,
}: BullButcherMapProps) {
  const [hoveredZoneId, setHoveredZoneId] = React.useState<string | null>(null);

  return (
    <svg viewBox="0 0 1024 553" className={className} role="img" aria-label="Bullen Zerlegekarte">
      <defs>
        <clipPath id="bullSilhouetteClip">
          <path d={BULL_SILHOUETTE_PATH} />
        </clipPath>
      </defs>

      <image href={imageHref} width="1024" height="553" preserveAspectRatio="xMidYMid meet" />

      <g clipPath="url(#bullSilhouetteClip)">
        {BULL_ZONES.map((zone) => {
          const isActive = zone.id === activeZoneId || zone.id === hoveredZoneId;
          return (
            <path
              key={zone.id}
              d={zone.path}
              fill={zone.color}
              fillOpacity={isActive ? 0.36 : 0}
              stroke={isActive ? "rgba(251,191,36,1)" : "rgba(245,158,11,0.78)"}
              strokeWidth={isActive ? 2.5 : 2}
              strokeDasharray="8 6"
              className="cursor-pointer transition-[fill-opacity,stroke,stroke-width] duration-200 ease-out"
              onMouseEnter={() => setHoveredZoneId(zone.id)}
              onMouseLeave={() => setHoveredZoneId((current) => (current === zone.id ? null : current))}
              onClick={() => onZoneClick?.(zone)}
            />
          );
        })}
      </g>

      {showLabels && (
        <g pointerEvents="none">
          {BULL_ZONES.map((zone) => (
            <text
              key={`${zone.id}-label`}
              x={zone.labelX}
              y={zone.labelY}
              textAnchor="middle"
              fontSize="13"
              fontWeight="700"
              letterSpacing="0.06em"
              fill="#F9FAFB"
              stroke="rgba(17,24,39,.78)"
              strokeWidth="3"
              paintOrder="stroke"
              style={{ fontFamily: "Inter, ui-sans-serif, system-ui, -apple-system, BlinkMacSystemFont, 'Segoe UI', sans-serif" }}
            >
              {zone.label}
            </text>
          ))}
        </g>
      )}
    </svg>
  );
}

export { BULL_ZONES, BULL_SILHOUETTE_PATH };
